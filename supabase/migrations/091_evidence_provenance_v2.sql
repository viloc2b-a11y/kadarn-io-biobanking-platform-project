-- ------ observations RLS ------

CREATE POLICY obs_select_institution ON public.observations
    FOR SELECT
    USING (
        institution_id IS NULL
        OR institution_id IN (
            SELECT organization_id FROM public.organization_memberships
            WHERE user_id = auth.uid() AND status = 'active'
        )
        OR auth.role() = 'service_role'
    );

CREATE POLICY obs_insert_institution ON public.observations
    FOR INSERT
    WITH CHECK (
        institution_id IS NULL
        OR institution_id IN (
            SELECT organization_id FROM public.organization_memberships
            WHERE user_id = auth.uid() AND status = 'active'
        )
        OR auth.role() = 'service_role'
    );

CREATE POLICY obs_update_institution ON public.observations
    FOR UPDATE
    USING (
        institution_id IS NULL
        OR institution_id IN (
            SELECT organization_id FROM public.organization_memberships
            WHERE user_id = auth.uid() AND status = 'active'
        )
        OR auth.role() = 'service_role'
    );

CREATE POLICY obs_all_service ON public.observations
    FOR ALL
    USING (auth.role() = 'service_role');

-- ------ evidence_links RLS ------

CREATE POLICY el_select_org ON public.evidence_links
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.evidence_nodes en
            WHERE en.id = evidence_links.evidence_node_id
            AND (
                en.visibility->>'owningOrganizationId' IN (
                    SELECT organization_id::text FROM public.organization_memberships
                    WHERE user_id = auth.uid() AND status = 'active'
                )
                OR auth.role() = 'service_role'
            )
        )
    );

CREATE POLICY el_insert_org ON public.evidence_links
    FOR INSERT
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.evidence_nodes en
            WHERE en.id = evidence_links.evidence_node_id
            AND en.visibility->>'owningOrganizationId' IN (
                SELECT organization_id::text FROM public.organization_memberships
                WHERE user_id = auth.uid() AND status = 'active'
            )
        )
        OR auth.role() = 'service_role'
    );

CREATE POLICY el_all_service ON public.evidence_links
    FOR ALL
    USING (auth.role() = 'service_role');

